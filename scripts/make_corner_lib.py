"""Write sim/ldo_corners.lib: one .lib section per corner with the structure of
the 'tt' section of sky130.lib.spice, so that only the 1.8 V devices get corner
files. Needed because the ss/ff/sf/fs sections of the raw sky130_fd_pr repo also
include a 5 V device file that ngspice 46 rejects ("Not enough parameters for
i source"). ll / hh = typical devices with low / high R and C."""
import os
import pathlib
import re

BASE = os.environ.get("SKY130_FD_PR", "path/to/sky130_fd_pr/models").rstrip("/") + "/"
ROOT = pathlib.Path(__file__).resolve().parent.parent
RC = {"tt": "typical__cap_typical", "ss": "typical__cap_typical", "ff": "typical__cap_typical",
      "sf": "typical__cap_typical", "fs": "typical__cap_typical",
      "ll": "low__cap_low", "hh": "high__cap_high"}


def main():
    lines = (pathlib.Path(BASE) / "sky130.lib.spice").read_text().splitlines()
    i0 = lines.index(".lib tt")
    i1 = next(i for i in range(i0, len(lines)) if lines[i].startswith(".endl"))
    body = [l for l in lines[i0:i1] if l.startswith(".include")]
    out = ["* LDO corner library (generated by make_corner_lib.py)", ""]
    for c, rc in RC.items():
        dc = c if c in ("tt", "ss", "ff", "sf", "fs") else "tt"
        out.append(f".lib {c}")
        for l in body:
            p = re.search(r'"(.*)"', l).group(1)
            p = p.replace("__tt.corner", f"__{dc}.corner").replace("corners/tt/", f"corners/{dc}/")
            p = p.replace("res_typical__cap_typical", f"res_{rc}")
            full = BASE + p
            if not pathlib.Path(full).exists():
                raise FileNotFoundError(full)
            out.append(f'.include "{full}"')
        out += [".endl", ""]
    (ROOT / "sim" / "ldo_corners.lib").write_text("\n".join(out))
    print("written", ROOT / "sim" / "ldo_corners.lib")


if __name__ == "__main__":
    main()
